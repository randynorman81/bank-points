"""Builds python/parsons-u3.js: 10 DIFFERENT Parsons problems per Unit 3 lesson (easy to hard). The different exercises already in the lesson (u3_base.json, taken from the earlier build, one per
distinct shape) plus the new ones in u3_more_a.py / u3_more_b.py. Every program is RUN, every wrong piece is tried in every line, every ordering is run. Nothing is written unless all checks pass.
Does NOT touch python/trace-u3.js (that is gen_u3tr.py).   usage: python3 tools/parsons/gen_u3pt.py"""
import sys, os, re, json, io, contextlib, itertools, random, runpy
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
ROOT = os.path.dirname(os.path.dirname(HERE))
src = open(os.path.join(HERE, 'gen_u3.py'), encoding='utf-8').read().split('P, T = {}, {}')[0]      # the helper functions of the old generator (nothing is written before this line)
G = {'__file__': os.path.join(HERE, 'gen_u3.py'), '__name__': 'gen_u3_helpers'}; exec(compile(src, 'gen_u3.py', 'exec'), G)
check_problem, describe, valid_orders, pieces_for, difficulty, LESSONS, errors = G['check_problem'], G['describe'], G['valid_orders'], G['pieces_for'], G['difficulty'], G['LESSONS'], G['errors']
from u3_more_a import MORE as MA
from u3_more_b import MORE as MB
MORE = dict(MA); MORE.update(MB)
BASE = json.load(open(os.path.join(HERE, 'u3_base.json'), encoding='utf-8'))
KW = {'print', 'input', 'int', 'float', 'str', 'len', 'find', 'True', 'False', 'type'}
def sig(lines):
    t = '\n'.join(lines); t = re.sub(r'"[^"]*"', 'S', t); t = re.sub(r'\b[A-Za-z_]\w*\b', lambda m: m.group(0) if m.group(0) in KW else 'V', t); return re.sub(r'\d+(\.\d+)?', 'N', t)
P = {}
for lid in LESSONS:
    base = LESSONS[lid]; cands = []; seen = set()
    for p in BASE[lid] + [dict(title=m['title'], story=m['story'], sol=m['sol'], distract=m['distract'], ins=m['ins']) for m in MORE.get(lid, [])]:
        s = sig(p['sol'])
        if s in seen: continue            # same exercise as one already in the lesson
        seen.add(s); cands.append(p)
    if len(cands) != 10: errors.append((lid, 'need 10 different exercises, have %d' % len(cands)))
    probs = []
    for k, hp in enumerate(cands):
        tag = '%s #%d' % (lid, k + 1)
        exp = check_problem(tag, hp['sol'], hp['distract'], [], hp['ins'])
        if exp is None: continue
        probs.append(dict(title=hp['title'], story=hp['story'], expect=exp, ins=hp['ins'], pieces=pieces_for(hp['sol'], hp['distract']), sol=hp['sol'], steps=[describe(l) for l in hp['sol']], valid=valid_orders(hp['sol'], hp['ins'], exp)))
    titles = [p['title'] for p in probs]
    if len(set(titles)) != len(titles): errors.append((lid, 'two problems share a title'))
    probs.sort(key=lambda p: difficulty(p['sol']))
    P[lid] = dict(num=base['num'], title=base['title'], brand=dict(name=base['brand'][0], color=base['brand'][1], head=base['brand'][2]), problems=probs)
if errors:
    for e in errors: print('PROBLEM', e)
    sys.exit(1)
dump = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
open(os.path.join(ROOT, 'python', 'parsons-u3.js'), 'w', encoding='utf-8').write('/* GENERATED by tools/parsons/gen_u3pt.py. Do not edit by hand. */\nwindow.PARSONS = ' + dump(dict(lessons=P)) + ';\n')
print('OK: %d lessons, %d Parsons, valid orders per problem min %d max %d' % (len(P), sum(len(v['problems']) for v in P.values()), min(len(p['valid']) for v in P.values() for p in v['problems']), max(len(p['valid']) for v in P.values() for p in v['problems'])))
