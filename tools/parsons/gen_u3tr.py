"""Writes python/trace-u3.js: ten different code-tracing programs per Unit 3 lesson (tools/parsons/u3_traces.py), traced by the same engine as Units 4 and 5.
Do NOT run tools/parsons/gen_u3.py any more: it would overwrite this file with the old 5-shapes-twice traces.   usage: python3 tools/parsons/gen_u3tr.py"""
import sys, os, re, json
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE); ROOT = os.path.dirname(os.path.dirname(HERE))
from u4_core import trace, run, check_problem, trace_difficulty
from u3_traces import TR3
META = [('u3l1', '3.1', 'Variable Names'), ('u3l2', '3.2', 'Storing Strings, Ints, Floats, and Booleans'), ('u3l3', '3.3', 'Getting Input From the User'), ('u3l4', '3.4', 'Joining Strings, Ints, Floats, and Booleans'),
        ('u3l5', '3.5', 'Indexing: Pulling One Character From a String'), ('u3l6', '3.6', 'Slicing: Pulling a Piece Out of a String'), ('u3l7', '3.7', 'Finding Text With .find()'), ('u3l8', '3.8', 'Math With Numbers From the User'),
        ('u3l9', '3.9', 'Division That Gives a Float ( / )'), ('u3l10', '3.10', 'Floor Division That Rounds Down ( // )'), ('u3l11', '3.11', 'Modulus: The Remainder ( % )'), ('u3l12', '3.12', 'Order of Operations'), ('u3l13', '3.13', 'Tracing Code by Hand')]
errors = []; T = {}
for lid, num, title in META:
    trs = []
    for ti, (code, ins) in enumerate(TR3[lid]):
        sol = code.split('\n'); tag = '%s T%d' % (lid, ti + 1)
        check_problem(tag, sol, [], ins, False, errors)
        steps, printed = trace(sol, ins)
        if run('\n'.join(sol), ins) != printed: errors.append((tag, 'trace output disagrees with a plain run'))
        asked = sum(1 for st in steps if (not st[5] and (st[0] or st[1])) or st[6])
        if asked < 2: errors.append((tag, 'only %d steps ask the student for anything' % asked))
        for st in steps:
            for v in st[0].values():
                if re.search(r'\d\.\d{6,}|e[+-]\d', v) or (v.startswith("'") and (v[1:-1] != v[1:-1].strip() or v == "''") and not st[5]) or (v.startswith("'") and ("\\" in v or '"' in v)): errors.append((tag, 'hard-to-type value ' + v))
            if not st[0] and not st[1] and not re.match(r'\s*(if|elif|while|for|def|break|import)\b', sol[st[3]]) and not st[4]: errors.append((tag, 'line %d changes nothing' % (st[3] + 1)))
        intro = 'Trace this program one line at a time. Work out what each line stores or prints.' + (' When it asks for input, the user types %s.' % ', '.join(ins) if ins else '')
        trs.append(dict(title='Trace %d' % (ti + 1), intro=intro, code=sol, ins=ins, steps=steps))
    trs.sort(key=lambda t: trace_difficulty(t['code'], t['steps']))      # easy to hard (stable)
    for k, t in enumerate(trs, 1): t['title'] = 'Trace %d' % k
    if len(trs) != 10: errors.append((lid, 'expected 10 traces'))
    T[lid] = dict(num=num, title=title, traces=trs)
if errors:
    for e in errors: print('PROBLEM', e)
    sys.exit(1)
open(os.path.join(ROOT, 'python', 'trace-u3.js'), 'w', encoding='utf-8').write('/* GENERATED by tools/parsons/gen_u3tr.py. Do not edit by hand. */\nwindow.TRACES = ' + json.dumps(T, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('OK: %d lessons, %d traces, %d steps' % (len(T), sum(len(v['traces']) for v in T.values()), sum(len(t['steps']) for v in T.values() for t in v['traces'])))
