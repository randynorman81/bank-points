/* BUNDLE the lesson assignment and game records (a101 to a193) into teacher-settings/python-records.js, so they go live with a deploy and need no PIN.
   usage: start the local dev server first:  node tools/missions/devserver.mjs 8124
          then:                              node tools/missions/bundle.mjs
   It publishes the records to the DEV server (PIN 1234, in memory) so they pass through the real save code, reads them back exactly as the server stores them, and writes the file. */
import { createRequire } from "module";
import fs from "fs";
const require = createRequire(import.meta.url);
const core = require("./index.js");
const BASE = process.env.API || "http://localhost:8124/api/pycode";
const call = async (body) => (await fetch(BASE, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(Object.assign({ pin: "1234" }, body)) })).json();
const recs = core.RECORDS.filter((r) => { const n = Number(r.slot.slice(1)); return n >= 101 && n <= 193; });
for (const r of recs) {
  const rec = r.rec;
  const up = await call({ action: "adminSetAssignment", slot: r.slot, title: rec.title, unit: rec.unit, num: rec.num, points: rec.points, blocks: rec.blocks, checks: rec.checks, tips: rec.tips, autoRun: rec.autoRun || [], game: rec.game, live: false });
  if (!up.ok) { console.error(r.slot, "save failed", JSON.stringify(up)); process.exit(1); }
  const set = { action: "adminSetLive", slot: r.slot, live: false, points: rec.points, seq: rec.seq };
  if (rec.part) set.part = rec.part;
  if (rec.passMin !== undefined) set.passMin = rec.passMin;
  const lv = await call(set); if (!lv.ok) { console.error(r.slot, "settings failed", JSON.stringify(lv)); process.exit(1); }
}
const all = (await call({ action: "adminAssignments" })).assignments || {};
const out = {}; recs.forEach((r) => { if (!all[r.slot]) throw new Error("missing " + r.slot); out[r.slot] = all[r.slot]; });
fs.writeFileSync(new URL("../../teacher-settings/python-records.js", import.meta.url), "/* GENERATED by tools/missions/bundle.mjs from the lesson assignment and game records (a101 to a193). Do not edit by hand: change the content in tools/missions and run the bundle again. */\nexport const PY_RECORDS = " + JSON.stringify(out) + ";\n");
console.log("bundled " + recs.length + " records, " + JSON.stringify(out).length + " characters");
